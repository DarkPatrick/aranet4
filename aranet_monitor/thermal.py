"""Outdoor "feels like": UTCI (Universal Thermal Climate Index) in the shade and in the sun.

UTCI (Jendritzky, Broede et al. 2012) is the equivalent air temperature at which a
reference person, walking in a reference environment, has the same physiological
response; it takes air temperature, humidity, wind at 10 m and the mean radiant
temperature (Tmrt). Shade: Tmrt = air temperature. Sun: Tmrt from the shortwave a
standing person absorbs (RayMan / VDI 3787 approach): global radiation is split into
direct and diffuse with the Erbs model, the direct beam hits the body's projected area
for the sun's elevation, half of the body sees the sky's diffuse light and half the
ground's reflection. Longwave from hot ground is left out, so the sun value is if
anything a bit low on summer afternoons.
"""

