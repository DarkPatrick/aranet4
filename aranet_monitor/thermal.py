def vapour_pressure_hpa(ta: float, rh: float) -> float:
    """Saturation vapour pressure over water (Hardy, ITS-90) times relative humidity."""
    tk = ta + 273.15
    g = [-2836.5744, -6028.076559, 19.54263612, -0.02737830188, 0.000016261698, 7.0229056e-10, -1.8680009e-13]
    es = 2.7150305 * math.log1p(tk) + sum(c * tk ** (i - 2) for i, c in enumerate(g))
    return math.exp(es) * 0.01 * rh / 100


def utci(ta, tmrt, wind10, rh) -> float | None:
    """degC; wind is clamped to the model's 0.5..17 m/s."""
    if ta is None or tmrt is None or wind10 is None or rh is None:
        return None
    v = min(max(wind10, 0.5), 17.0)
    dt, pa = tmrt - ta, vapour_pressure_hpa(ta, rh) / 10
    return round(ta + sum(c * ta ** a * v ** b * dt ** d * pa ** e for c, a, b, d, e in UTCI_TERMS), 1)


def category(u: float) -> str:
    return next(name for top, name in CATEGORIES if u < top)


def sun_elevation(ts: float, lat: float, lon: float) -> float:
    """Degrees; the same low-precision ephemeris as the dashboard's sun chart."""
    rad = math.pi / 180
    d = ts / 86400 - 0.5 + 2440588 - 2451545
    m = rad * (357.5291 + 0.98560028 * d)
    c = rad * (1.9148 * math.sin(m) + 0.02 * math.sin(2 * m) + 0.0003 * math.sin(3 * m))
    lam = m + c + rad * 102.9372 + math.pi
    e = rad * 23.4397
    dec = math.asin(math.sin(e) * math.sin(lam))
    ra = math.atan2(math.sin(lam) * math.cos(e), math.cos(lam))
    h = rad * (280.16 + 360.9856235 * d) + rad * lon - ra
    phi = rad * lat
    return math.asin(math.sin(phi) * math.sin(dec) + math.cos(phi) * math.cos(dec) * math.cos(h)) / rad


def split_radiation(ghi: float, elevation: float, ts: float) -> tuple[float, float]:
    """Global horizontal -> (direct normal, diffuse horizontal), W/m2, Erbs et al. 1982."""
    if ghi <= 0:
        return 0.0, 0.0
    if elevation < 2:  # the sun at the horizon: treat everything as diffuse
        return 0.0, ghi
    doy = datetime.fromtimestamp(ts, timezone.utc).timetuple().tm_yday
    sin_h = math.sin(math.radians(elevation))
    i0 = SOLAR_CONST * (1 + 0.033 * math.cos(2 * math.pi * doy / 365)) * sin_h
    kt = min(ghi / i0, 1.0)
    kd = (1 - 0.09 * kt if kt <= 0.22 else
          0.9511 - 0.1604 * kt + 4.388 * kt ** 2 - 16.638 * kt ** 3 + 12.336 * kt ** 4 if kt <= 0.8 else 0.165)
    dhi = kd * ghi
    return min((ghi - dhi) / sin_h, 1100.0), dhi


def tmrt_sun(ta: float, ghi: float, elevation: float, ts: float) -> float:
    """Mean radiant temperature of a standing person in full sun, degC."""
    dni, dhi = split_radiation(ghi, elevation, ts)
    h = max(elevation, 0.0)
    fp = 0.308 * math.cos(math.radians(h * (0.998 - h * h / 50000)))  # projected area factor, standing
    shortwave = fp * dni + 0.5 * dhi + 0.5 * ALBEDO * ghi
    return ((ta + 273.15) ** 4 + ABSORB / (EMISS * SIGMA) * shortwave) ** 0.25 - 273.15


def feels(ta, rh, wind10, ghi, lat, lon, ts) -> tuple[float | None, float | None]:
    """(UTCI in the shade, UTCI in the sun). Without radiation (or at night) the sun
    value equals the shade one."""
    shade = utci(ta, ta, wind10, rh)
    if shade is None:
        return None, None
    elev = sun_elevation(ts, lat, lon)
    if not ghi or ghi <= 0 or elev <= 0:
        return shade, shade
    return shade, utci(ta, tmrt_sun(ta, ghi, elev, ts), wind10, rh)
